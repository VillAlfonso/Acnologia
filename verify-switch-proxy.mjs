try {
 await auto.startRecording({...store.state.workflows[0],startUrl:'http://proxy.invalid/'});
 const old = auto.recorder;
 await old.page.locator('#name').fill('Alice');
 await old.context.addCookies([{name:'test',value:'kept',url:'http://proxy.invalid/'}]);
 const closed = await old.context.newPage(); await closed.close();
 const second = await old.context.newPage(); await second.goto('http://proxy.invalid/second');
 await second.locator('#name').fill('Bob');
 auto.pauseRecording(true);
 const fields=JSON.stringify(old.fields), steps=JSON.stringify(old.steps);
 const result=await auto.switchRecordingProxy();
 assert.equal(result.status,'paused'); assert.equal(result.exitIP,'1.1.1.1');
 assert.equal(JSON.stringify(auto.recorder.steps),steps); assert.equal(JSON.stringify(auto.recorder.fields),fields);
 assert.equal(auto.recorder.bindings,old.bindings);
 assert.equal(auto.recorder.pages.length,3); assert.ok(auto.recorder.pages[1].isClosed());
 assert.equal(auto.recorder.page,auto.recorder.pages[2]);
 assert.ok((await auto.recorder.context.cookies()).some(c=>c.name==='test'));
 assert.equal(old.browser.isConnected(),false);
 const kept=auto.recorder; ip='9.9.9.9';
 await assert.rejects(auto.switchRecordingProxy(),/matches the direct IP/);
 assert.equal(auto.recorder,kept); assert.equal(kept.status,'paused'); assert.ok(kept.browser.isConnected());
 await writeFile(path.join(root,'proxy.json'),JSON.stringify({mode:'direct'}));
 await assert.rejects(auto.switchRecordingProxy(),/No proxy configured/);
 console.log('PASS: switch, generator fields/bindings, actions, cookies, tab indexes, pause state, rollback and direct-mode rejection.');
} finally { await auto.shutdown(); await store.queue; proxy.closeAllConnections(); await new Promise(resolve=>proxy.close(resolve)); }
