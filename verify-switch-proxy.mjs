import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { Store } from 'file:///C:/BrowserAuto/source-switch-proxy-20261115/lib/store.js';
import { Automation } from 'file:///C:/BrowserAuto/source-switch-proxy-20261115/lib/automation.js';
const root = await mkdtemp(path.join(os.tmpdir(), 'browserauto-base-switch-'));
let ip = '1.1.1.1';
const proxy = createServer((req,res) => { res.setHeader('Content-Type', req.url.endsWith('/ip') ? 'text/plain' : 'text/html'); res.end(req.url.endsWith('/ip') ? ip : '<input id="name"><p>Test</p>'); });
await new Promise(resolve => proxy.listen(0,'127.0.0.1',resolve));
const store = new Store(root); await store.init('http://127.0.0.1:4310');
await writeFile(path.join(root,'proxy.json'),JSON.stringify({server:`http://127.0.0.1:${proxy.address().port}`}));
